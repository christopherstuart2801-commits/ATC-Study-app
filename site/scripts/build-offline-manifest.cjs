#!/usr/bin/env node
/* Enumerate the real shell files and the publication PDFs the app already references.
   No globs are written into the service worker. */
const fs = require('fs');
const path = require('path');

const VERSION = '0.8.37';
const SITE = path.join(__dirname, '..');

const SHELL = [
  'index.html',
  'manifest.webmanifest',
  'offline/core.js',
  'offline/backup.js',
  'offline/client.js',
  'offline/head-guide.js',
  'offline/manifest.js',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
  'icons/apple-touch-icon.png',
  'data/para-index.json',
  'data/ref-span.json',
  'data/ask-aliases.json',
  'vendor/pdfjs/pdf.min.js',
  'vendor/pdfjs/pdf.worker.min.js'
];

function pdfHrefs(html) {
  const out = [];
  /* JS objects use href:'…'; the plate list is JSON and uses "href":"…". */
  const re = /(?:href:|"href":)['"](docs\/[A-Za-z0-9._/-]+\.pdf)['"]/g;
  let m;
  while ((m = re.exec(html))) out.push(m[1]);
  return [...new Set(out)].sort();
}

function enumerate() {
  const html = fs.readFileSync(path.join(SITE, 'index.html'), 'utf8');
  const missing = [];
  SHELL.forEach(rel => {
    if (rel === 'offline/manifest.js') return;
    if (!fs.existsSync(path.join(SITE, rel))) missing.push(rel);
  });
  const lazy = pdfHrefs(html);
  lazy.forEach(rel => {
    if (!fs.existsSync(path.join(SITE, rel))) missing.push(rel);
  });
  if (missing.length) {
    const err = new Error('offline manifest missing files: ' + missing.join(', '));
    err.missing = missing;
    throw err;
  }
  const banned = /(^|\/)[^/]+\.(md|txt)$|\.\.|supabase|\/api\/|^api\//i;
  const all = SHELL.concat(lazy);
  all.forEach(rel => {
    if (banned.test(rel) || /^https?:/i.test(rel) || rel.indexOf('*') >= 0) {
      throw new Error('refusing offline path ' + rel);
    }
  });
  return {
    version: VERSION,
    precache: SHELL.slice(),
    lazy: lazy
  };
}

function emit(manifest) {
  return '/* Generated by scripts/build-offline-manifest.cjs. Enumerated paths only. */\n' +
    'self.VATC_MANIFEST = ' + JSON.stringify(manifest, null, 2) + ';\n';
}

function main() {
  const manifest = enumerate();
  const file = path.join(SITE, 'offline', 'manifest.js');
  fs.writeFileSync(file, emit(manifest));
  console.log('offline manifest', manifest.version, 'precache', manifest.precache.length, 'lazy', manifest.lazy.length);
}

module.exports = { enumerate, emit, VERSION, SHELL };

if (require.main === module) main();
